const generateRecords = (memberId: string, courseId: string, courseTitle: string, category: string, daysAgo: number): WorkoutRecord => {
  const date = new Date(Date.now() - daysAgo * 86400000);
  const completionRate = Math.floor(Math.random() * 30) + 70;
  const duration = Math.floor(Math.random() * 10) + 15;
  return {
    id: `r_${memberId}_${courseId}_${daysAgo}`,
    memberId,
    courseId,
    courseTitle,
    courseCategory: category as any,
    date: date.toISOString().split('T')[0],
    duration,
    completionRate,
    calories: Math.floor(duration * 8),
    totalExercises: 6,
    completedExercises: Math.floor(6 * completionRate / 100),
  };
};

